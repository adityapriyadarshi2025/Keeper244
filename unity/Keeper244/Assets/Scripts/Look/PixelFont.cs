        /// <summary>True if pixel (col, row) of the glyph is lit. Row 0 is the top. Unknown characters are blank.</summary>
        public static bool Lit(char c, int col, int row)
        {
            if (!Glyphs.TryGetValue(char.ToUpperInvariant(c), out var g)) return false;
            return g[row][col] == '#';
        }

        /// <summary>Width of a text in dots, with one blank column between glyphs.</summary>
        public static int Measure(string text) => text.Length * (Width + 1);
    }
